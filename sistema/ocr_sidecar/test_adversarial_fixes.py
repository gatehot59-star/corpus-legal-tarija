def page(text="NO PAGAR"):
    """Independent page fixture with literal expected content."""
    return {"page": 1, "status": "requires_review", "blank_by_pixels": False,
            "text": text, "blocks": [{"index": 0, "label": "text", "text": text}]}


def full_result():
    """Explicit expected envelope, not generated by the function under test."""
    return {"schema": "corpus-ocr/1", "status": "requires_review",
            "expected_pages": 1, "completed_pages": 1, "fidelity_certified": False,
            "pages": [page()], "text": "NO PAGAR",
            "markdown": "<!-- page:1 -->\nNO PAGAR"}


def make_pdf(path, native=True, raster=True):
    """Build a page with separate native prose and raster-only legal clause."""
    writer = PdfWriter()
    p = writer.add_blank_page(width=612, height=792)
    font = DictionaryObject({NameObject("/Type"): NameObject("/Font"),
                             NameObject("/Subtype"): NameObject("/Type1"),
                             NameObject("/BaseFont"): NameObject("/Helvetica")})
    resources = DictionaryObject({NameObject("/Font"): DictionaryObject({
        NameObject("/F1"): writer._add_object(font)})})
    commands = []
    if native:
        commands = ["BT /F1 12 Tf 40 740 Td"] + [
            "(Texto nativo legal para clasificar esta pagina de prueba.) Tj 0 -16 Td"
            for _ in range(9)] + ["ET"]
    if raster:
        with Image.new("RGB", (1000, 150), "white") as image:
            ImageDraw.Draw(image).text((15, 40), "NO PAGAR Bs20.000.000",
                                      fill="black", font_size=40)
            obj = DecodedStreamObject()
            obj.set_data(image.tobytes())
            obj.update({NameObject("/Type"): NameObject("/XObject"),
                        NameObject("/Subtype"): NameObject("/Image"),
                        NameObject("/Width"): NumberObject(image.width),
                        NameObject("/Height"): NumberObject(image.height),
                        NameObject("/ColorSpace"): NameObject("/DeviceRGB"),
                        NameObject("/BitsPerComponent"): NumberObject(8)})
        resources[NameObject("/XObject")] = DictionaryObject({
            NameObject("/Im0"): writer._add_object(obj)})
        commands.append("q 500 0 0 75 40 400 cm /Im0 Do Q")
    p[NameObject("/Resources")] = resources
    stream = DecodedStreamObject()
    stream.set_data("\n".join(commands).encode())
    p[NameObject("/Contents")] = writer._add_object(stream)
    try:
        with path.open("wb") as f:
            writer.write(f)
    finally:
        writer.close()


class Fixes(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix="ocr-fix-regression-")
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)

    def plan(self, native, raster, mode="auto"):
        source = self.root / "fixture.pdf"
        make_pdf(source, native, raster)
        work = self.root / "work"
        work.mkdir(exist_ok=True)
        return s.prepare_pages(source, "pdf", mode, work)

    def test_native_only_positive(self):
        plan = self.plan(True, False)
        self.assertTrue(plan[0][2])
        self.assertIsNone(plan[0][3])

    def test_mixed_same_page_routes_ocr_and_preserves_native(self):
        plan = self.plan(True, True)
        self.assertNotIn("NO PAGAR", plan[0][1])
        self.assertGreater(len(plan[0][1]), 200)
        self.assertFalse(plan[0][2], "raster legal clause must not disappear")
        self.assertTrue(plan[0][3].is_file())

    def test_txt_mixed_rejected_instead_of_silent_loss(self):
        with self.assertRaisesRegex(ValueError, "native_text_not_usable"):
            self.plan(True, True, "txt")

    def test_scan_and_forced_ocr_positive(self):
        self.assertFalse(self.plan(False, True)[0][2])
        self.assertFalse(self.plan(True, False, "ocr")[0][2])

    def test_image_inventory_fails_closed(self):
        with patch.object(s, "run_command", return_value="unexpected output"):
            with self.assertRaisesRegex(ValueError, "invalid_image_inventory"):
                s.page_has_raster(self.root / "fixture.pdf", 1)

    def test_image_inventory_masks_count_as_raster(self):
        for kind in ("image", "mask", "smask"):
            with patch.object(s, "run_command", return_value=(
                    "page num type width height\n--------------------------\n"
                    f"1 0 {kind} 100 100\n")):
                self.assertTrue(s.page_has_raster(self.root / "fixture.pdf", 1))

    def test_nonblank_positive_and_blank_positive(self):
        self.assertEqual(s.complete_document([page()], 1)["text"], "NO PAGAR")
        blank = page("")
        blank.update(blank_by_pixels=True, blocks=[])
        self.assertEqual(s.complete_document([blank], 1)["text"], "")

    def test_empty_and_whitespace_blocks_rejected(self):
        for text in ("", " \n\t", "\u00a0"):
            with self.subTest(text=repr(text)):
                with self.assertRaisesRegex(ValueError, "empty_nonblank_output"):
                    s.complete_document([page(text)], 1)

    def test_worker_final_progress(self):
        job, runtime = self.root / "job", self.root / "runtime"
        job.mkdir()
        runtime.mkdir()
        make_pdf(job / "input", True, False)
        s.atomic(job / "request.json", {"kind": "pdf", "mode": "auto",
                 "input_sha256": s.digest(job / "input"), "runtime_seal": "double"})
        (runtime / "pipeline.yaml").write_text(
            '{"SubModules":{"LayoutDetection":{},"VLRecognition":{}}}')
        with patch.object(s, "verify_job_runtime", return_value={
                "models": [], "config_sha256": "double"}), \
             patch.dict(sys.modules, {"yaml": types.SimpleNamespace(safe_load=json.loads)}), \
             patch.object(s.resource, "setrlimit"):
            s.worker(job, runtime)
        result = s.read_json(job / "result.json")
        progress = s.read_json(job / "progress.json")
        self.assertEqual(result["completed_pages"], 1)
        self.assertEqual(progress["completed_pages"], 1)
        self.assertEqual(progress["phase"], "completed")
        self.assertFalse((job / "work").exists())

    def supervise(self, child="pass", result=None, timeout=1, partial=None):
        """Run real supervisor/real child; replace only the worker command."""
        root = self.root / ("jobs-" + str(time.monotonic_ns()))
        root.mkdir()
        jobs = object.__new__(s.Jobs)
        jobs.root, jobs.runtime = root, self.root
        jobs.timeout, jobs.stopping, jobs.failure = timeout, False, None
        jobs.queue = queue.Queue()
        ident = "a" * 32
        job = root / ident
        job.mkdir()
        if result is not None:
            s.atomic(job / "result.json", result)
        if partial is not None:
            s.atomic(job / "partial.json", partial)
            s.atomic(job / "progress.json", {"phase": "extraction",
                     "completed_pages": 0, "expected_pages": partial["expected_pages"]})
        real_popen, children = subprocess.Popen, []
        def launch(*args, **kwargs):
            process = real_popen([sys.executable, "-c", child], **kwargs)
            children.append(process)
            return process
        with patch.object(s.subprocess, "Popen", side_effect=launch):
            thread = threading.Thread(target=jobs.loop)
            thread.start()
            jobs.queue.put(ident)
            try:
                deadline = time.monotonic() + 5
                while time.monotonic() < deadline:
                    if jobs.queue.unfinished_tasks == 0:
                        return s.read_json(job / "state.json"), job
                    time.sleep(.01)
                self.fail("instrument deadline")
            finally:
                jobs.stopping = True
                thread.join(3)
                for process in children:
                    if process.poll() is None:
                        os.killpg(process.pid, signal.SIGKILL)
                    process.wait(timeout=2)
                self.assertFalse(thread.is_alive(), "supervisor thread leaked")

    def test_supervisor_valid_envelope_positive(self):
        state, job = self.supervise(result=full_result())
        self.assertEqual(state["status"], "requires_review")
        self.assertIsNone(state["error"])
        progress = s.read_json(job / "progress.json")
        self.assertEqual(progress["completed_pages"], 1)

    def test_supervisor_rejects_each_aggregate_mutation(self):
        for field, value in (("text", "PAGAR"), ("markdown", "PAGAR"),
                             ("fidelity_certified", True), ("completed_pages", 0),
                             ("status", "certified"), ("schema", "unknown")):
            with self.subTest(field=field):
                mutant = full_result()
                mutant[field] = value
                state, _ = self.supervise(result=mutant)
                self.assertEqual(state["status"], "failed")
                self.assertEqual(state["error"], "invalid_worker_result")

    def test_supervisor_missing_field_rejected(self):
        result = full_result()
        del result["text"]
        state, _ = self.supervise(result=result)
        self.assertEqual(state["status"], "failed")
        self.assertEqual(state["error"], "invalid_worker_result")

    def test_result_endpoint_revalidates_after_state_completed(self):
        import test_ocr_service
        harness = test_ocr_service.HttpTests("test_liveness_readiness")
        harness.setUp()
        try:
            job = harness.jobs.root / ("b" * 32)
            job.mkdir()
            s.atomic(job / "state.json", {"status": "requires_review"})
            s.atomic(job / "result.json", full_result())
            path = "/v1/jobs/" + "b" * 32 + "/result"
            self.assertEqual(harness.request("GET", path)[0], 200)
            mutant = full_result()
            mutant["text"] = "PAGAR"
            s.atomic(job / "result.json", mutant)
            status, body = harness.request("GET", path)
            self.assertEqual(status, 409)
            self.assertEqual(body["error"], "invalid_worker_result")
        finally:
            harness.doCleanups()

    def test_sigkill_is_not_timeout(self):
        state, _ = self.supervise("import os,signal; os.kill(os.getpid(),signal.SIGKILL)")
        self.assertEqual(state["worker_exit"], -9)
        self.assertEqual(state["error"], "worker_signal")
        self.assertEqual(state["signal"], 9)
        self.assertFalse(state["timed_out"])

    def test_actual_timeout_positive(self):
        state, _ = self.supervise("import time; time.sleep(30)", timeout=.15)
        self.assertEqual(state["error"], "timeout")
        self.assertEqual(state["worker_exit"], -9)
        self.assertTrue(state["timed_out"])

    def test_failure_progress_preserves_completed_partial(self):
        partial = {"status": "incomplete", "pages": [page()], "expected_pages": 2,
                   "fidelity_certified": False}
        state, job = self.supervise("raise SystemExit(1)", partial=partial)
        self.assertEqual(state["status"], "failed")
        progress = s.read_json(job / "progress.json")
        self.assertEqual(progress["phase"], "failed")
        self.assertEqual(progress["completed_pages"], 1)
        self.assertEqual(progress["expected_pages"], 2)


